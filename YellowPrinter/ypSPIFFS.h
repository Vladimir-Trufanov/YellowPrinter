/*
 Что за ошибка "SPIFFS: mount failed, -10025"
 
 Ошибка SPIFFS: mount failed, -10025 возникает при попытке подключить файловую систему SPIFFS на ESP32. 
 Код -10025 указывает на то, что система не смогла найти или инициализировать раздел флеш-памяти, 
 предназначенный для SPIFFS. 

 Возможные причины:
 
 - Некорректная таблица разделов. Если вы изменили параметры раздела (например, увеличили размер SPIFFS 
 в файле partitions.csv), но не перекомпилировали скетч с новыми настройками, ESP32 может пытаться 
 найти раздел по старому адресу, которого больше нет. 

 - Проблемы с физическим подключением. Ненадёжные контакты (например, при использовании макетных проводов 
 вместо пайки) могут мешать работе SPI-шины.
  
 - Повреждение файловой системы. Иногда SPIFFS может повредиться, например, из-за нестабильного питания. 
 
 - Конфликт с другими библиотеками. В некоторых случаях проблема может быть связана с использованием 
 альтернативной файловой системы (например, LittleFS) вместо SPIFFS.
 
 Как решить проблему:
 
 1. Проверьте таблицу разделов. Если вы меняли файл partitions.csv (например, для использования большего 
 объёма SPIFFS), убедитесь, что новая таблица корректно описывает раздел и его расположение в памяти. 
 Возможно, потребуется перекомпиляция скетча с новыми параметрами. 
 
 2 !!!. Принудительное форматирование при ошибке. В коде можно явно указать, что при неудаче нужно отформатировать SPIFFS. 
 Для этого вызовите функцию SPIFFS.begin() с параметром true: SPIFFS.begin(true). Однако учтите, что это сотрёт все 
 существующие данные на SPIFFS. 
 
 3. Проверьте физическое подключение. Убедитесь, что все SPI-линии (MOSI, MISO, SCK, CS) надёжно соединены. 
 При использовании макетных проводов или проводов от прототипирования лучше перепаять соединения на пайку. 
 
 4. Проверьте питание. Нестабильное или недостаточное питание может приводить к ошибкам при работе с SPI-шиной. 
 Убедитесь, что питание стабильное. 
 
 5. Рассмотрите переход на LittleFS. Если проблема сохраняется, можно попробовать заменить библиотеку SPIFFS на LittleFS в коде. 

 Начните с проверки таблицы разделов и параметра formatOnFail. Если это не поможет, проверьте физическое подключение и питание. 
 Если и это не решит проблему, возможно, стоит рассмотреть переход на другую файловую систему (например, LittleFS). 
*/

/*
 if (!SPIFFS.begin()) 
 { 
    while (1) yield(); 
 }
 
 Этот фрагмент кода проверяет, успешно ли инициализировалась файловая система SPIFFS на микроконтроллерах ESP 
 (например, ESP32 или ESP8266), и в случае неудачи останавливает выполнение программы. 
 
 Как это работает. SPIFFS.begin() — это функция из библиотеки для работы с файловой системой SPIFFS. 
 Она пытается инициализировать её (подключить к памяти устройства). Если инициализация провалится 
 (например, из-за того, что файловая система не была заранее подготовлена или возникла аппаратная ошибка), 
 функция вернёт false.
 
 if (!SPIFFS.begin()) — это условная конструкция. Если SPIFFS.begin() вернула false, условие в if считается выполненным, 
 и управление передаётся внутрь блока кода.
 
 while (1) yield(); — это бесконечный цикл, который не делает ничего полезного, а просто «запирает» процессор. 
 Функция yield() (или task::yield() в контексте FreeRTOS) отдаёт управление другим задачам (прерываниям обрабатываются), 
 позволяя системе не «зависнуть» полностью, но при этом программа точно не продолжит работу дальше.
 
 Зачем так делают. Такая конструкция — стандартный способ обработки критических ошибок инициализации 
 в проектах на Arduino с ESP. Если SPIFFS не удалось запустить, программа не продолжит работу, а зависнет, 
 давая возможность диагностировать проблему (например, проверить, правильно ли была подготовлена файловая
 система при загрузке прошивки). Часто в блоке кода также добавляют вывод сообщения об ошибке через Serial.println(). 
 
 Важный нюанс. Стоит помнить, что бесконечный цикл с yield() потребляет ресурсы процессора. В некоторых ресурсоограниченных 
 проектах это может быть критично. Альтернативой иногда служит вызов ESP.restart() или abort(), но у каждого подхода 
 есть свои нюансы. Таким образом, этот фрагмент — надёжный способ сигнализировать о критической 
 ошибке на этапе запуска и предотвратить дальнейшее непредсказуемое поведение программы.
*/

/*
 if (!SPIFFS.begin(true)) 
 { 
    while (1) yield(); 
 }

 Как это работает. SPIFFS.begin(true) пытается подключить файловую систему SPIFFS. Параметр true означает, 
 что система будет смонтирована (подключена) сразу, без дополнительных действий со стороны программиста. 
 Если при подключении возникает ошибка (например, флеш-память повреждена), метод возвращает false. 

 Строка Serial.println("Ошибка инициализации SPIFFS!") может вывести диагностическое сообщение в последовательный порт, 
 чтобы разработчик мог понять причину сбоя. 
*/

// Инициализировать SPIFFS
void iniSPIFFS()
{
  if (!SPIFFS.begin(true)) 
  //if (!SPIFFS.begin()) 
  {
    while (1) yield();
  }  
}


